// gen-noscript.mjs — build the static <noscript> fallback from the section
// JSON and splice it into index.html between the NOSCRIPT markers.
//
// The site renders everything client-side, so without JavaScript there is
// nothing for a crawler, a link preview, or a reader-mode pass to read. Rather
// than hand-maintaining a second copy of the resume, generate it from the same
// data the terminal renders and commit the result: no build step at serve time,
// and test/noscript.test.js fails when index.html drifts from the data.
//
//   node tools/gen-noscript.mjs        # rewrite index.html
//   node tools/gen-noscript.mjs --check  # exit 1 if it would change
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { DATES_RE, entries as flatten } from "../js/sections-model.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const BEGIN = "<!-- NOSCRIPT:BEGIN (generated by tools/gen-noscript.mjs) -->";
export const END = "<!-- NOSCRIPT:END -->";

// Section links must survive into the fallback, so keep inline HTML.
const entries = block => flatten(block, { keepHtml: true });

// Everything but the authored <a> lines is plain text from JSON, so escape it.
// The negative lookahead leaves existing entities alone.
function esc(s) {
  return s
    .replace(/&(?![a-zA-Z#][a-zA-Z0-9]*;)/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

// Render one section block. `subheads` names the classes that introduce a
// group in this section — a company, a school, a project, a skills category —
// which become headings; every other accented line is emphasis, not structure,
// so a tagline or a contact row stays a paragraph. Bullets are collected into
// a <ul> so the list is a list to a screen reader and to a crawler.
function blockHtml(block, { headingLevel = 2, subheads = [] } = {}) {
  const out = [];
  let bullets = [];
  const flushBullets = () => {
    if (bullets.length) out.push(`<ul>\n${bullets.join("\n")}\n</ul>`);
    bullets = [];
  };
  for (const e of entries(block)) {
    if (e.cls === "line-bullet") {
      bullets.push(`<li>${esc(e.text)}</li>`);
      continue;
    }
    flushBullets();
    // "APPLE 2018 - Present" and friends: split the right-aligned date column
    // off rather than leaving a run of spaces in the markup.
    const m = DATES_RE.exec(e.text);
    const body = m
      ? `${esc(m[1])} <span class="dates">${esc(m[2])}</span>`
      : esc(e.text);
    if (e.cls === "line-heading") {
      out.push(`<h${headingLevel}>${body}</h${headingLevel}>`);
    } else if (subheads.includes(e.cls)) {
      out.push(`<h${headingLevel + 1}>${body}</h${headingLevel + 1}>`);
    } else if (e.cls === "line-link") {
      // Authored HTML — the anchor is the point of the line.
      out.push(`<p class="link">${e.text}</p>`);
    } else if (e.cls === "line-accent" || e.cls === "line-highlight") {
      out.push(`<p><strong>${body}</strong></p>`);
    } else {
      out.push(`<p>${body}</p>`);
    }
  }
  flushBullets();
  return out;
}

export function noscriptHtml(sections, experience) {
  const parts = [
    "<noscript>",
    '<div id="noscript">',
    "<h1>Benjamin Nied</h1>",
    '<p class="role">Site Reliability Engineer</p>',
    '<p class="note">This site is an interactive terminal and needs JavaScript.' +
      " What follows is the same resume as plain text.</p>",
  ];
  // What counts as a group heading differs per section: a skills category, a
  // company, a project, a school. Anything not named here stays a paragraph.
  parts.push(...blockHtml(sections.about));
  parts.push(...blockHtml(sections.contact));
  parts.push(...blockHtml(sections.skills, { subheads: ["line-highlight"] }));
  parts.push(...blockHtml(sections.experience, { subheads: ["line-accent"] }));
  // The experience section lists the roles; the detail blocks hold the bullets.
  for (const block of Object.values(experience)) {
    parts.push(...blockHtml(block, { headingLevel: 3 }));
  }
  parts.push(...blockHtml(sections.projects, { subheads: ["line-accent"] }));
  parts.push(...blockHtml(sections.education, { subheads: ["line-accent"] }));
  parts.push("</div>", "</noscript>");
  return parts.join("\n");
}

export function buildIndex(html, sections, experience) {
  const start = html.indexOf(BEGIN);
  const stop = html.indexOf(END);
  if (start === -1 || stop === -1) {
    throw new Error("index.html is missing the NOSCRIPT markers");
  }
  const body = noscriptHtml(sections, experience);
  return html.slice(0, start) + BEGIN + "\n" + body + "\n" + html.slice(stop);
}

export function readSources() {
  const json = f => JSON.parse(readFileSync(join(ROOT, f), "utf8"));
  return {
    html: readFileSync(join(ROOT, "index.html"), "utf8"),
    sections: json("data/sections.json"),
    experience: json("data/experience.json"),
  };
}

// Run directly: rewrite index.html, or --check that it is already current.
if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const { html, sections, experience } = readSources();
  const next = buildIndex(html, sections, experience);
  if (process.argv.includes("--check")) {
    if (next !== html) {
      console.error("index.html is stale — run: node tools/gen-noscript.mjs");
      process.exit(1);
    }
    console.log("index.html noscript block is current");
  } else if (next === html) {
    console.log("index.html noscript block already current");
  } else {
    writeFileSync(join(ROOT, "index.html"), next);
    console.log("index.html noscript block updated");
  }
}
